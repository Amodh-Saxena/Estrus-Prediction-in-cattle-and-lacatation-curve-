def load_pdf_labels_df() -> pd.DataFrame:
    """Return tidy dataframe of ground truth estrus events: columns [animal_id, date, session, estrus]."""
    rows = []
    seen = set()
    for date_str, am_csv, pm_csv in PDF_ESTRUS_TABLE_4PAGES:
        for aid in [x.strip() for x in am_csv.split(",") if x.strip()]:
            key = (aid, date_str)
            if key not in seen:
                seen.add(key)
                rows.append({"animal_id": aid, "date": date_str, "session": "AM_08_09", "estrus": 1})
        for aid in [x.strip() for x in pm_csv.split(",") if x.strip()]:
            key = (aid, date_str)
            if key not in seen:
                seen.add(key)
                rows.append({"animal_id": aid, "date": date_str, "session": "PM_15_16", "estrus": 1})
    df = pd.DataFrame(rows)
    df["date"] = pd.to_datetime(df["date"]).dt.normalize()
    return df.sort_values(["animal_id", "date"]).reset_index(drop=True)


def build_pdf_lookup() -> dict[str, list[dict[str, str]]]:
    """Map animal_id to list of {'date': YYYY-MM-DD, 'session': AM/PM} events."""
    lookup = defaultdict(list)
    df = load_pdf_labels_df()
    for _, r in df.iterrows():
        lookup[str(r["animal_id"])].append({
            "date": r["date"].strftime("%Y-%m-%d"),
            "session": r["session"],
        })
    return dict(lookup)

